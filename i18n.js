let LANG = (function () {
  const saved = localStorage.getItem("qf_lang");
  if (saved === "en" || saved === "es") return saved;
  return (navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
})();

function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
}
function tPhrase(str) { return LANG === "es" ? (ES_PHRASE[str] || str) : str; }
function tBrand(b) { return LANG === "es" ? (ES_BRAND[b] || b) : b; }
function tIssue(i) { return LANG === "es" ? (ES_ISSUE[i] || i) : i; }

function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.getAttribute("data-i18n-html")); });
  const label = document.getElementById("lang-label");
  if (label) label.textContent = LANG === "en" ? "ES" : "EN";
  if (typeof window.renderDynamic === "function") window.renderDynamic();
}
function setLang(l) {
  LANG = l; localStorage.setItem("qf_lang", l); applyI18n();
}

document.getElementById("lang-toggle")?.addEventListener("click", () => setLang(LANG === "en" ? "es" : "en"));
